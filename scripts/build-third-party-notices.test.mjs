test('builds a deterministic index from production dependencies and reviewed data', () => {
  const result = buildThirdPartyNotices(packageLock, reviewedData);

  assert.deepEqual(result.generatedFrom, {
    data: 'config/third-party-data.json',
    software: 'package-lock.json#packages[""].dependencies',
  });
  assert.deepEqual(result.software.map((entry) => entry.name), ['alpha', 'zebra']);
  assert.deepEqual(result.data.map((entry) => entry.name), ['Cliopatria', 'Historical Basemaps']);
  assert.equal(result.software.some((entry) => entry.name === 'test_only'), false);
  assert.deepEqual(result.software[0], {
    name: 'alpha',
    version: '1.4.0',
    license: 'ISC',
    source: 'https://registry.npmjs.org/alpha/-/alpha-1.4.0.tgz',
    attribution: 'Package: alpha',
  });
});

