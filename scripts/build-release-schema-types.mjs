import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath, pathToFileURL } from 'node:url';

const defaultSchemaUrl = new URL('../src/content/release-schema.json', import.meta.url);
const defaultGeneratedUrl = new URL('../src/content/release-schema.generated.ts', import.meta.url);

export function renderReleaseSchemaModule(schema) {
  const serialized = JSON.stringify(schema, null, 2)
    .replaceAll('\u2028', '\\u2028')
    .replaceAll('\u2029', '\\u2029');
  return `// Generated by scripts/build-release-schema-types.mjs from release-schema.json.\n`
    + `// Do not edit this file directly.\n`
    + `import type { JSONSchema } from 'json-schema-to-ts';\n\n`
    + `const releaseSchema = ${serialized} as const satisfies JSONSchema;\n\n`
    + `export default releaseSchema;\n`;
}

export async function generateReleaseSchemaTypes({
  schemaPath = fileURLToPath(defaultSchemaUrl),
  generatedPath = fileURLToPath(defaultGeneratedUrl),
} = {}) {
  const schema = JSON.parse(await readFile(schemaPath, 'utf8'));
  const output = renderReleaseSchemaModule(schema);
  await writeFile(generatedPath, output);
  return output;
}

export async function verifyGeneratedReleaseSchema({
  schemaPath = fileURLToPath(defaultSchemaUrl),
  generatedPath = fileURLToPath(defaultGeneratedUrl),
} = {}) {
  const schema = JSON.parse(await readFile(schemaPath, 'utf8'));
  const expected = renderReleaseSchemaModule(schema);
  const actual = await readFile(generatedPath, 'utf8');
  if (actual !== expected) {
    throw new Error('Generated release schema type mirror is out of date; run npm run build:release-schema-types');
  }
}

async function main() {
  if (process.argv.slice(2).includes('--check')) {
    await verifyGeneratedReleaseSchema();
    return;
  }
  await generateReleaseSchemaTypes();
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch((error) => {
    console.error(error instanceof Error ? error.message : error);
    process.exitCode = 1;
  });
}
